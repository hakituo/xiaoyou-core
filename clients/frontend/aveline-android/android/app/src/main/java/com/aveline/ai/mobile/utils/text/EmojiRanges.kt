package com.aveline.ai.mobile.utils.text

/**
 * Emoji Unicode 范围表与判定。
 *
 * 用途：硬边界标点（。！?…）后紧跟的 emoji 要粘到当前句尾，不能被断到下一句开头。
 * 范围与 Python 端 `core/utils/text_segmenter.py` 的 `EMOJI_RANGES` 一一对应，

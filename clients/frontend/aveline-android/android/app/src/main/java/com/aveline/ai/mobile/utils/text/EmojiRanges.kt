        0xE0020, 0xE007F,
    )

    /** 判断单个码点是否是 emoji。 */
    fun isEmojiCodePoint(cp: Int): Boolean {
        var i = 0
        while (i < RANGES.size) {
            if (cp in RANGES[i]..RANGES[i + 1]) return true
            i += 2
        }
        return false
    }
}

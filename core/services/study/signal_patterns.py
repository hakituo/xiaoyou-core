# 语气/指示前缀：normalize 的 strip_prefix 用。**只做结构性剥离，不判语义**
#
# 分两类，**剥离条件不同**（矩阵 v3 逐例验证过，改之前先跑
# ``.tmp/check_matrix_conformance.py``）：
#
#   A. ``_STRIP_PREFIXES``（无条件剥，词本身就是语气/指示）：
#      哼哼 -> 猜猜看     那个 -> 感觉      那 -> 奶头和胸
#
#   B. ``_DISCOURSE_MARKERS``（**仅当片段位于整条消息开头时才剥**）：
#      不过 / 其实 / 这样吗 / 然后 / 就是
#      它们是**标记句与句之间关系**的转折/承接词，本身不属于「它实际说的那一段」；
#      但只在**句首**才起这个作用——出现在逗号之后时它属于**前一句**，
#      剥掉会改变后一句的语义范围（矩阵 R-05 vs R-07 的分界）。
#
#      矩阵依据：
#        R-07「不过那个时候的学生为什么…」   片段在**句首** → 剥 → 「那个时候的学生」
#        R-05「…，不过你头发为什么是紫色的…」片段在**逗号后** → 保留 → 「不过你头发」
